import { expect, test } from "@playwright/test";

// Pages use mock data here (see playwright.config.ts): the saving of the
// answers is covered by the unit tests and the API tests.
test("starts the diagnostic from the dashboard and answers with the keyboard", async ({
    page,
}) => {
    await page.goto("/dashboard");
    await page.getByRole("link", { name: "Faire un diagnostic" }).click();

    await expect(page).toHaveURL(/\/diagnostic$/);
    await expect(
        page.getByRole("heading", {
            name: "Faisons le point sur votre démarche QHSE",
        }),
    ).toBeVisible();

    await page.getByRole("button", { name: "Commencer le diagnostic" }).click();
    const question = page.getByRole("heading", {
        name: "Votre entreprise a-t-elle fixé des objectifs qualité mesurables ?",
    });
    await expect(question).toBeFocused();
    await expect(page.getByText("Question 1 sur 8")).toBeVisible();

    // The choices are a real radio group: Tab, then the arrows.
    await page.keyboard.press("Tab");
    await page.keyboard.press("Space");
    await expect(page.getByRole("radio", { name: "Oui" })).toBeChecked();
    await page.keyboard.press("ArrowRight");
    await expect(page.getByRole("radio", { name: "En partie" })).toBeChecked();

    await page.getByRole("button", { name: "Suivant" }).click();
    await expect(page.getByText("Question 2 sur 8")).toBeVisible();

    await page.getByRole("button", { name: "Voir le récapitulatif" }).click();
    await expect(
        page.getByRole("heading", { name: "Récapitulatif" }),
    ).toBeVisible();
    await expect(
        page.getByRole("button", { name: "Valider le diagnostic" }),
    ).toBeDisabled();
});

test("shows the score of the latest diagnostic, also as a table", async ({
    page,
}) => {
    await page.goto("/diagnostic/resultat");

    await expect(
        page.getByRole("heading", { name: "Résultat du diagnostic" }),
    ).toBeVisible();
    await expect(
        page.getByRole("img", { name: "Score global : 62 sur 100" }),
    ).toBeVisible();
    await expect(page.getByText("Maîtrisé")).toBeVisible();
    await expect(
        page.getByRole("heading", { name: "Actions prioritaires" }),
    ).toBeVisible();

    const table = page.getByRole("table");
    await expect(table).toBeHidden();
    await page.getByText("Voir tous les scores sous forme de tableau").click();
    await expect(table).toBeVisible();
    await expect(
        table.getByRole("row", { name: /Score global 62/ }),
    ).toBeVisible();

    // The dashboard shows the same score.
    await page.goto("/dashboard");
    await expect(
        page.getByRole("img", { name: "Score global : 62 sur 100" }),
    ).toBeVisible();
});

test("downloads the summary of the result as a PDF", async ({ page }) => {
    // The PDF is generated by the API (covered by its tests): simulated here.
    await page.route("**/diagnostic-files/1", (route) =>
        route.fulfill({
            status: 200,
            headers: {
                "Content-Type": "application/pdf",
                "Content-Disposition":
                    "attachment; filename=reglo-diagnostic-2026-10-12.pdf",
            },
            body: "%PDF-1.7\n",
        }),
    );
    await page.goto("/diagnostic/resultat");

    const download = page.waitForEvent("download");
    await page
        .getByRole("link", { name: "Télécharger la synthèse (PDF)" })
        .click();

    expect((await download).suggestedFilename()).toBe(
        "reglo-diagnostic-2026-10-12.pdf",
    );
});

test("asks before starting a new diagnostic, and can be cancelled", async ({
    page,
}) => {
    await page.goto("/diagnostic/resultat");

    const restart = page.getByRole("button", { name: "Refaire un diagnostic" });
    await restart.click();
    const dialog = page.getByRole("dialog", {
        name: "Refaire un diagnostic ?",
    });
    await expect(dialog).toContainText("restent dans l'historique");
    await page.keyboard.press("Escape");

    await expect(dialog).toBeHidden();
    await expect(restart).toBeFocused();
});

test("goes through the history to an older result", async ({ page }) => {
    await page.goto("/diagnostic/resultat");

    await page
        .getByRole("link", { name: "Historique des diagnostics" })
        .click();
    await expect(page).toHaveURL(/\/diagnostic\/historique$/, {
        timeout: 30_000,
    });
    await expect(
        page.getByRole("heading", { name: /Diagnostic du 12 oct\. 2026/ }),
    ).toBeVisible();

    await page
        .getByRole("link", { name: "Voir le résultat du 1 juil. 2026" })
        .click();

    await expect(page).toHaveURL(/\/diagnostic\/historique\/0$/, {
        timeout: 30_000,
    });
    await expect(
        page.getByRole("heading", {
            level: 1,
            name: "Diagnostic du 1 juil. 2026",
        }),
    ).toBeVisible();
    await expect(
        page.getByRole("img", { name: "Score global : 57 sur 100" }),
    ).toBeVisible();
});
